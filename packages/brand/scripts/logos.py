"""Regenerates the logo outlines (src/logo-paths.mjs) and SVG files (assets/logo/) from Space Grotesk Bold.
Needs Python with fontTools:  python3 scripts/logos.py path/to/SpaceGrotesk-Bold.ttf
Then run `npm run build`."""
import json, sys, os
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
sys.path.insert(0, root)
font = TTFont(sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, 'fonts', 'SpaceGrotesk-Bold.ttf'))
gs = font.getGlyphSet(); cmap = font.getBestCmap(); hm = font['hmtx']; upm = font['head'].unitsPerEm
TRACK = -0.03 * upm  # letter-spacing -0.03em, as in the CSS wordmark

def layout(text):
    x, items = 0, []
    for ch in text:
        g = cmap[ord(ch)]; items.append((g, x)); x += hm[g][0] + TRACK
    return items

def build(text):
    items = layout(text)
    xs, ys = [], []
    for g, x in items:
        b = BoundsPen(gs); gs[g].draw(b)
        if b.bounds: xs += [x + b.bounds[0], x + b.bounds[2]]; ys += [b.bounds[1], b.bounds[3]]
    minx, miny, maxx, maxy = min(xs), min(ys), max(xs), max(ys)
    def path(g, x):
        p = SVGPathPen(gs, ntos=lambda v: ('%.1f' % v).rstrip('0').rstrip('.'))
        gs[g].draw(TransformPen(p, (1, 0, 0, -1, x - minx, maxy)))
        return p.getCommands()
    letters = ' '.join(path(g, x) for g, x in items[:-1])
    dot = path(*items[-1])
    return {'width': round(maxx - minx), 'height': round(maxy - miny), 'letters': letters, 'dot': dot}

logo = {'wordmark': build('mintsy.'), 'mark': build('m.')}
with open(os.path.join(root, 'src', 'logo-paths.mjs'), 'w') as f:
    f.write('// Generated by scripts/logos.py from Space Grotesk Bold. Do not edit.\n')
    f.write('// Coordinates in font units (1000/em); viewBox = 0 0 width height.\n')
    f.write('export const logoPaths = ' + json.dumps(logo, indent=2) + ';\n')

# SVG files
import subprocess
tokens = json.loads(subprocess.check_output(['node', '-e', "import('%s/src/tokens.mjs').then(m=>console.log(JSON.stringify({themes:m.themes})))" % root.replace('\\', '/')]))
os.makedirs(os.path.join(root, 'assets', 'logo'), exist_ok=True)
def svg(kind, letters_fill, dot_fill, title='mintsy'):
    L = logo[kind]
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {L["width"]} {L["height"]}" role="img" aria-label="{title}">'
            f'<title>{title}</title><path fill="{letters_fill}" d="{L["letters"]}"/><path fill="{dot_fill}" d="{L["dot"]}"/></svg>\n')
for kind in logo:
    open(os.path.join(root, 'assets', 'logo', f'{kind}.svg'), 'w').write(svg(kind, 'currentColor', 'currentColor'))
    for name, t in tokens['themes'].items():
        open(os.path.join(root, 'assets', 'logo', f'{kind}-{name}-on-dark.svg'), 'w').write(svg(kind, t['dark']['foreground'], t['dark']['brand']))
        open(os.path.join(root, 'assets', 'logo', f'{kind}-{name}-on-light.svg'), 'w').write(svg(kind, t['dark']['primaryForeground'], t['light']['brand']))
print('logos written')
