// ─── Native (NativeWind 5 / react-native-css, gluestack) ──────────────
const nativeKeys = colorKeys; // same names as the app's global.css, in kebab-case
const nativeBlock = (c, indent) =>
  nativeKeys.map((k) => `${indent}--${kebab(k)}: ${triplet(c[k])};`).join('\n');
for (const name of themeNames) {
  const t = T.themes[name];
  out(`css/native/${name}.css`, HEADER + `/* ${t.label} for the mobile app (NativeWind). Values are "r g b" triplets, used as rgb(var(--x)).
   Light on :root; dark under prefers-color-scheme, which NativeWind maps to the device appearance. */
@layer theme {
  :root {
${nativeBlock(t.light, '    ')}
  }

  @media (prefers-color-scheme: dark) {
    :root {
${nativeKeys.filter((k) => t.dark[k] !== t.light[k]).map((k) => `      --${kebab(k)}: ${triplet(t.dark[k])};`).join('\n')}
    }
  }
}
`);
  out(`css/native/${name}.web.css`, HEADER + `/* ${t.label}: web-only overrides so gluestack can force light/dark with a class on <html>.
   Native rejects class-qualified :root selectors, so this lives in its own file. */
:root.dark {
${nativeBlock(t.dark, '  ')}
}

:root.light {
${nativeBlock(t.light, '  ')}
}
`);
}
out('css/native/tailwind.css', HEADER + `/* Tailwind utilities for the mobile app: bg-brand, text-faint, font-display…
   Import AFTER a theme file, e.g.
     @import "@mintsy/brand/css/native/${T.defaultTheme}.css";
     @import "@mintsy/brand/css/native/tailwind.css"; */
@theme inline {
${nativeKeys.map((k) => `  --color-${kebab(k)}: rgb(var(--${kebab(k)}));`).join('\n')}

  /* Each weight is its own family name (expo-font registers them separately) */
  --font-inter: ${T.fonts.body.native[400]};
  --font-inter-medium: ${T.fonts.body.native[500]};
  --font-inter-semibold: ${T.fonts.body.native[600]};
  --font-inter-bold: ${T.fonts.body.native[700]};
  --font-display: ${T.fonts.display.native[700]};
  --font-display-medium: ${T.fonts.display.native[500]};
}
`);
