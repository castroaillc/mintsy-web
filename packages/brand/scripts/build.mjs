// Generates dist/ (JS, CJS, types, JSON) and css/ from src/tokens.mjs.
// No dependencies: `node scripts/build.mjs`.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as T from '../src/tokens.mjs';
import { logoPaths } from '../src/logo-paths.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const HEADER = '/* Generated by @mintsy/brand (scripts/build.mjs) from src/tokens.mjs. Do not edit. */\n';
const out = (rel, text) => {
  const p = join(root, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, text);
};

const kebab = (s) => s.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase());
const rgb = (hex) => {
  const n = parseInt(hex.slice(1), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
};
const triplet = (hex) => rgb(hex).join(' ');
const css = (hex, alpha) => `rgb(${triplet(hex)}${alpha ? ` / ${alpha}` : ''})`;
const themeNames = Object.keys(T.themes);

// ─── JS ──────────────────────────────────────────────────────────────
const data = {
  brand: T.brand,
  defaultTheme: T.defaultTheme,
  defaultMode: T.defaultMode,
  themes: T.themes,
  collage: T.collage,
  coverInk: T.coverInk,
  fonts: T.fonts,
  logo: T.logo,
  radius: T.radius,
  spacing: T.spacing,
  logoPaths,
};
const helpers = `
function hexToRgb(hex) {
  var n = parseInt(String(hex).replace('#', ''), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}
function rgba(hex, alpha) {
  var c = hexToRgb(hex);
  return 'rgba(' + c[0] + ', ' + c[1] + ', ' + c[2] + ', ' + alpha + ')';
}
function getTheme(name, mode) {
  var t = themes[name || defaultTheme];
  if (!t) throw new Error('@mintsy/brand: unknown theme "' + name + '". Use one of: ' + Object.keys(themes).join(', '));
  return t[mode || defaultMode];
}
function tintFor(index, name) {
  var list = themes[name || defaultTheme].tints;
  return list[((index % list.length) + list.length) % list.length];
}
function coverInkFor(tone) {
  var c = hexToRgb(tone);
  return 0.299 * c[0] + 0.587 * c[1] + 0.114 * c[2] > 150 ? coverInk.onLight : coverInk.onDark;
}
`;
const names = [...Object.keys(data), 'hexToRgb', 'rgba', 'getTheme', 'tintFor', 'coverInkFor'];
const consts = Object.entries(data)
  .map(([k, v]) => `var ${k} = ${JSON.stringify(v, null, 2)};`)
  .join('\n');
out('dist/index.js', `// Generated by @mintsy/brand. Do not edit.\n${consts}\n${helpers}\nexport { ${names.join(', ')} };\n`);
out('dist/index.cjs', `// Generated by @mintsy/brand. Do not edit.\n'use strict';\n${consts}\n${helpers}\nmodule.exports = { ${names.join(', ')} };\n`);
out('dist/tokens.json', JSON.stringify(data, null, 2) + '\n');

const colorKeys = Object.keys(T.themes[T.defaultTheme].dark);
const dts = `// Generated by @mintsy/brand. Do not edit.
export type ThemeName = ${themeNames.map((n) => `'${n}'`).join(' | ')};
export type Mode = 'dark' | 'light';
export type HexColor = \`#\${string}\`;
export interface ThemeColors {
${colorKeys.map((k) => `  ${k}: HexColor;`).join('\n')}
}
export interface Theme {
  label: string;
  dark: ThemeColors;
  light: ThemeColors;
  /** Hero, player and episode-card backdrops (always dark panels). */
  tints: HexColor[];
  iconBackground: HexColor;
  splashBackground: HexColor;
}
export interface FontFamily {
  family: string;
  weights: number[];
  stack: string;
  native: Record<number, string> | null;
}
export declare const brand: {
  name: string; wordmark: string; tagline: string; description: string;
  domain: string; url: string; supportEmail: string; appScheme: string;
};
export declare const defaultTheme: ThemeName;
export declare const defaultMode: Mode;
export declare const themes: Record<ThemeName, Theme>;
export declare const collage: Record<${Object.keys(T.collage).map((k) => `'${k}'`).join(' | ')}, HexColor>;
export declare const coverInk: { onLight: HexColor; onDark: HexColor };
export declare const fonts: { display: FontFamily; body: FontFamily; condensed: FontFamily };
export declare const logo: { letterSpacing: string; weight: number; minSize: { px: number }; clearSpace: string };
export declare const radius: { sm: number; md: number; lg: number; xl: number; pill: number; web: string };
export declare const spacing: { gutter: number; section: number; maxWidth: number };
export interface LogoPath { width: number; height: number; letters: string; dot: string }
/** Vector outlines of the logo (Space Grotesk Bold), for react-native-svg, Remotion or inline SVG. viewBox = 0 0 width height. */
export declare const logoPaths: { wordmark: LogoPath; mark: LogoPath };
export declare function hexToRgb(hex: string): [number, number, number];
export declare function rgba(hex: string, alpha: number): string;
/** Colors for a theme and mode. Defaults: '${T.defaultTheme}', '${T.defaultMode}'. */
export declare function getTheme(name?: ThemeName, mode?: Mode): ThemeColors;
/** The backdrop tint for the nth item (wraps around). */
export declare function tintFor(index: number, name?: ThemeName): HexColor;
/** Readable text color on a cover of the given color. */
export declare function coverInkFor(tone: string): HexColor;
`;
out('dist/index.d.ts', dts);
out('dist/index.d.cts', dts);

// ─── Web (Tailwind v4 + shadcn/ui, plain CSS) ─────────────────────────
function webVars(c, t) {
  const brand60 = css(c.brand, '60%');
  const v = {
    background: c.background,
    foreground: c.foreground,
    card: c.card,
    'card-foreground': c.foreground,
    popover: c.popover,
    'popover-foreground': c.popoverForeground,
    primary: c.brand,
    'primary-foreground': c.brandForeground,
    secondary: c.secondary,
    'secondary-foreground': c.secondaryForeground,
    muted: c.muted,
    'muted-foreground': c.mutedForeground,
    accent: c.accent,
    'accent-foreground': c.accentForeground,
    destructive: c.destructive,
    border: c.border,
    input: c.input,
    ring: brand60,
    'chart-1': c.brand,
    'chart-2': c.mutedForeground,
    'chart-3': c.faint,
    'chart-4': c.ring,
    'chart-5': c.borderStrong,
    sidebar: c.card,
    'sidebar-foreground': c.foreground,
    'sidebar-primary': c.brand,
    'sidebar-primary-foreground': c.brandForeground,
    'sidebar-accent': c.accent,
    'sidebar-accent-foreground': c.accentForeground,
    'sidebar-border': c.border,
    'sidebar-ring': brand60,
    brand: c.brand,
    'brand-foreground': c.brandForeground,
    'brand-on-light': c.brandOnLight,
    'surface-raised': c.surfaceRaised,
    tag: c.tag,
    faint: c.faint,
    'border-strong': c.borderStrong,
    success: c.success,
    scrim: c.scrim,
    'on-scrim': c.onScrim,
    'on-tint': c.onTint,
    'neutral-strong': c.primary,
    'neutral-strong-foreground': c.primaryForeground,
  };
  t.tints.forEach((h, i) => (v[`tint-${i + 1}`] = h));
  return Object.entries(v)
    .map(([k, val]) => `  --${k}: ${val.startsWith('#') ? css(val) : val};`)
    .join('\n');
}
const sel = (theme, mode) => {
  const isDefault = theme === T.defaultTheme;
  if (mode === 'dark') return isDefault ? [':root', `[data-theme="${theme}"]`] : [`[data-theme="${theme}"]`];
  const base = isDefault ? [':root', `[data-theme="${theme}"]`] : [`[data-theme="${theme}"]`];
  return base.flatMap((b) => [`${b}.light`, `${b}[data-mode="light"]`]);
};
let web = HEADER + `/* mintsy themes for the web (admin).
   Default: ${T.defaultTheme}, dark. Pick a theme with data-theme on <html>:
     <html data-theme="ink-coral">
   Light mode: class="light" or data-mode="light"; follow the OS with data-mode="system".
   shadcn's --primary is the brand color here; --neutral-strong is the app's neutral "primary". */

:root {
  --mintsy-font-display: ${T.fonts.display.stack};
  --mintsy-font-body: ${T.fonts.body.stack};
  --mintsy-font-condensed: ${T.fonts.condensed.stack};
  --radius: ${T.radius.web};
${Object.entries(T.collage).map(([k, h]) => `  --collage-${k}: ${css(h)};`).join('\n')}
}
`;
for (const mode of ['dark', 'light']) {
  for (const name of themeNames) {
    const t = T.themes[name];
    web += `\n/* ${t.label} · ${mode} */\n${sel(name, mode).join(',\n')} {\n  color-scheme: ${mode};\n${webVars(t[mode], t)}\n}\n`;
  }
}
for (const name of themeNames) {
  const t = T.themes[name];
  const base = name === T.defaultTheme ? [':root', `[data-theme="${name}"]`] : [`[data-theme="${name}"]`];
  web += `\n@media (prefers-color-scheme: light) {\n  ${base.map((b) => `${b}[data-mode="system"]`).join(',\n  ')} {\n    color-scheme: light;\n${webVars(t.light, t).replace(/^/gm, '  ')}\n  }\n}\n`;
}
out('css/web.css', web);

