#!/usr/bin/env node
// Generates the iOS app's brand resources from packages/brand (and two constants from packages/shared), plus the
// per-variant app icons from design/icons, so nothing is hand-copied:
//   Mintsy/Resources/Brand.xcassets          color sets (light + dark), wordmark and mark (SVG), app icon per variant
//   Mintsy/Brand/Palette.generated.swift     the color sets as Swift constants, episode tints, cover ink, radii
//   Mintsy/Brand/BrandFontName.generated.swift  PostScript names of the bundled fonts (read from the TTF files)
//   Mintsy/Catalog/SharedConstants.generated.swift  FREE_EPISODES and the category list
// The fonts themselves aren't copied: project.yml bundles them straight from packages/brand/fonts.
//
// Usage: node scripts/generate-brand.mjs           write the files
//        node scripts/generate-brand.mjs --check   exit 1 if any generated file is out of date (CI, before a build)

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const iosRoot = path.resolve(here, '..');
const repoRoot = path.resolve(iosRoot, '../..');
const brandRoot = path.join(repoRoot, 'packages/brand');
const sharedRoot = path.join(repoRoot, 'packages/shared');

const { themes, defaultTheme, fonts, radius, coverInk } = await import(pathToFileURL(path.join(brandRoot, 'src/tokens.mjs')).href);
const { CATEGORIES, FREE_EPISODES } = await import(pathToFileURL(path.join(sharedRoot, 'index.js')).href);

const check = process.argv.includes('--check');
const theme = themes[defaultTheme];
const HEADER = '// Generated by apps/ios/scripts/generate-brand.mjs from packages/brand and packages/shared. Do not edit.\n';

/** path (relative to apps/ios) → contents (string or Buffer) */
const outputs = new Map();
const out = (rel, contents) => outputs.set(rel, contents);

// ── Colors ──────────────────────────────────────────────────────────

/** "#FF6B57" → { r, g, b } in 0...1, as the strings Xcode writes. */
function components(hex) {
  const n = parseInt(hex.slice(1), 16);
  const c = (v) => (v / 255).toFixed(3);
  return { red: c((n >> 16) & 255), green: c((n >> 8) & 255), blue: c(n & 255) };
}

const colorEntry = (hex, appearance) => ({
  ...(appearance ? { appearances: [{ appearance: 'luminosity', value: appearance }] } : {}),
  color: { 'color-space': 'srgb', components: { alpha: '1.000', ...components(hex) } },
  idiom: 'universal',
});

const json = (value) => `${JSON.stringify(value, null, 2)}\n`;
const info = { author: 'xcode', version: 1 };
const upperFirst = (s) => s.charAt(0).toUpperCase() + s.slice(1);

const catalog = 'Mintsy/Resources/Brand.xcassets';
out(`${catalog}/Contents.json`, json({ info }));
out(`${catalog}/Colors/Contents.json`, json({ info, properties: { 'provides-namespace': false } }));

const tokenNames = Object.keys(theme.dark);
for (const name of tokenNames) {
  const light = theme.light[name];
  if (!light) throw new Error(`packages/brand: "${name}" has a dark value but no light one`);
  // "Any" is the light value so a light mode can be added later; the app currently pins dark (RootView)
  out(
    `${catalog}/Colors/${upperFirst(name)}.colorset/Contents.json`,
    json({ colors: [colorEntry(light), colorEntry(theme.dark[name], 'dark')], info }),
  );
}
// Launch screen background (Info.plist UILaunchScreen → UIColorName)
out(`${catalog}/Colors/LaunchBackground.colorset/Contents.json`, json({ colors: [colorEntry(theme.splashBackground)], info }));

// ── Logo and icon ───────────────────────────────────────────────────

/** The SVG for each appearance: dark ink on light, light ink on dark. */
function logoImageSet(name, base) {
  const dir = `${catalog}/Logo/${name}.imageset`;
  const lightFile = `${base}-ink-coral-on-light.svg`;
  const darkFile = `${base}-ink-coral-on-dark.svg`;
  out(`${dir}/${lightFile}`, readFileSync(path.join(brandRoot, 'assets/logo', lightFile)));
  out(`${dir}/${darkFile}`, readFileSync(path.join(brandRoot, 'assets/logo', darkFile)));
  out(
    `${dir}/Contents.json`,
    json({
      images: [
        { filename: lightFile, idiom: 'universal' },
        { appearances: [{ appearance: 'luminosity', value: 'dark' }], filename: darkFile, idiom: 'universal' },
      ],
      info,
      properties: { 'preserves-vector-representation': true, 'template-rendering-intent': 'original' },
    }),
  );
}
out(`${catalog}/Logo/Contents.json`, json({ info, properties: { 'provides-namespace': false } }));
logoImageSet('Wordmark', 'wordmark');
logoImageSet('Mark', 'mark');

// One 1024 px icon per variant; Xcode derives the other sizes. The inputs are design/icons (icon.png for
// Production, icon-dev.png and icon-preview.png for the other two), and each xcconfig picks its set with
// ASSETCATALOG_COMPILER_APPICON_NAME. Only the chosen set is compiled into the app.
const iconsDir = path.join(iosRoot, 'design/icons');
const appIcons = [
  { set: 'AppIcon', file: 'icon.png' },
  { set: 'AppIcon-Dev', file: 'icon-dev.png' },
  { set: 'AppIcon-Preview', file: 'icon-preview.png' },
];

/** Throws unless the PNG is 1024 × 1024 with no alpha channel (App Store icons can't have one). */
function checkIcon(file, data) {
  const rel = path.relative(iosRoot, file);
  if (data.toString('latin1', 1, 4) !== 'PNG' || data.toString('latin1', 12, 16) !== 'IHDR') throw new Error(`${rel} isn't a PNG`);
  const width = data.readUInt32BE(16);
  const height = data.readUInt32BE(20);
  if (width !== 1024 || height !== 1024) throw new Error(`${rel} is ${width}×${height}; app icons must be 1024×1024`);
  // Color types 4 (gray + alpha) and 6 (RGBA) carry alpha; a tRNS chunk adds it to the others
  const colorType = data.readUInt8(25);
  let hasTRNS = false;
  for (let at = 8; at + 8 <= data.length; ) {
    const length = data.readUInt32BE(at);
    const type = data.toString('latin1', at + 4, at + 8);
    if (type === 'tRNS') hasTRNS = true;
    if (type === 'IEND') break;
    at += 12 + length;
  }
  if (colorType === 4 || colorType === 6 || hasTRNS) throw new Error(`${rel} has an alpha channel; app icons can't`);
}

for (const { set, file } of appIcons) {
  const source = path.join(iconsDir, file);
  const data = readFileSync(source);
  checkIcon(source, data);
  out(`${catalog}/${set}.appiconset/${file}`, data);
  out(
    `${catalog}/${set}.appiconset/Contents.json`,
    json({ images: [{ filename: file, idiom: 'universal', platform: 'ios', size: '1024x1024' }], info }),
  );
}

// The Production icon is the brand icon. Flag it when packages/brand moves on without design/icons/icon.png.
const brandIcon = path.join(brandRoot, 'assets/icons', defaultTheme, 'icon.png');
const iconDrift = Buffer.compare(readFileSync(brandIcon), readFileSync(path.join(iconsDir, 'icon.png'))) !== 0
  ? [`design/icons/icon.png (differs from ${path.relative(repoRoot, brandIcon)}: copy the new brand icon over it)`]
  : [];

// ── Swift: palette ──────────────────────────────────────────────────

const swiftColor = (hex) => {
  const { red, green, blue } = components(hex);
  return `Color(red: ${red}, green: ${green}, blue: ${blue})`;
};

const palette = [
  HEADER,
  'import SwiftUI',
  '',
  `/// Brand colors (theme "${defaultTheme}"). Each adapts to light and dark from the asset catalog.`,
  'nonisolated enum Palette {',
  ...tokenNames.map(
    (name) =>
      `    /// Dark ${theme.dark[name]}, light ${theme.light[name]}\n    static let ${name} = Color("${upperFirst(name)}")`,
  ),
  '',
  '    /// Hero, player and episode-card backdrops (always dark panels), rotated by episode number.',
  `    static let episodeTints: [Color] = [${theme.tints.map(swiftColor).join(', ')}]`,
  '',
  '    /// Text on a book cover: dark ink on light covers, cream on dark ones.',
  `    static let coverInkOnLight = ${swiftColor(coverInk.onLight)}`,
  `    static let coverInkOnDark = ${swiftColor(coverInk.onDark)}`,
  '}',
  '',
  '/// Corner radii from packages/brand.',
  'nonisolated enum BrandRadius {',
  ...Object.entries(radius)
    .filter(([, v]) => typeof v === 'number')
    .map(([k, v]) => `    static let ${k}: Double = ${v}`),
  '}',
  '',
].join('\n');
out('Mintsy/Brand/Palette.generated.swift', palette);

// ── Swift: font names ───────────────────────────────────────────────

/** The PostScript name (name ID 6) of a TrueType font, which is what Font.custom needs. */
function postScriptName(file) {
  const data = readFileSync(file);
  const tables = data.readUInt16BE(4);
  for (let i = 0; i < tables; i++) {
    const rec = 12 + 16 * i;
    if (data.toString('latin1', rec, rec + 4) !== 'name') continue;
    const offset = data.readUInt32BE(rec + 8);
    const count = data.readUInt16BE(offset + 2);
    const strings = offset + data.readUInt16BE(offset + 4);
    for (let j = 0; j < count; j++) {
      const r = offset + 6 + 12 * j;
      const platform = data.readUInt16BE(r);
      if (data.readUInt16BE(r + 6) !== 6) continue;
      const bytes = data.subarray(strings + data.readUInt16BE(r + 10), strings + data.readUInt16BE(r + 10) + data.readUInt16BE(r + 8));
      if (platform === 1) return bytes.toString('latin1');
      // UTF-16BE
      return Buffer.from(bytes).swap16().toString('utf16le');
    }
  }
  throw new Error(`${file} has no PostScript name`);
}

const weightNames = { 400: 'regular', 500: 'medium', 600: 'semibold', 700: 'bold' };
const fontFiles = readdirSync(path.join(brandRoot, 'fonts')).filter((f) => f.endsWith('.ttf'));
const fontLines = [];
for (const [role, spec] of [['display', fonts.display], ['body', fonts.body]]) {
  const prefix = spec.family.replace(/\s+/g, '');
  for (const weight of spec.weights) {
    const suffix = { 400: 'Regular', 500: 'Medium', 600: 'SemiBold', 700: 'Bold' }[weight];
    const file = `${prefix}-${suffix}.ttf`;
    if (!fontFiles.includes(file)) throw new Error(`packages/brand/fonts/${file} is missing (${spec.family} ${weight})`);
    fontLines.push(`    static let ${role}${upperFirst(weightNames[weight])} = "${postScriptName(path.join(brandRoot, 'fonts', file))}"`);
  }
}
out(
  'Mintsy/Brand/BrandFontName.generated.swift',
  [
    HEADER,
    `/// PostScript names of the fonts in packages/brand/fonts: display is ${fonts.display.family}, body is ${fonts.body.family}.`,
    'nonisolated enum BrandFontName {',
    ...fontLines,
    '}',
    '',
  ].join('\n'),
);

// ── Swift: shared constants ─────────────────────────────────────────

out(
  'Mintsy/Catalog/SharedConstants.generated.swift',
  [
    HEADER,
    '/// Constants shared with the backend and the other apps (packages/shared).',
    'nonisolated enum SharedConstants {',
    '    /// Episodes 1...freeEpisodes of every book are free; later ones need Premium.',
    `    static let freeEpisodes = ${FREE_EPISODES}`,
    '    /// The categories the app can filter by. A book in any other category never matches a chip.',
    `    static let categories: [String] = [${CATEGORIES.map((c) => JSON.stringify(c)).join(', ')}]`,
    '}',
    '',
  ].join('\n'),
);

// ── Write or check ──────────────────────────────────────────────────

const same = (file, contents) => existsSync(file) && Buffer.compare(readFileSync(file), Buffer.from(contents)) === 0;

/** Files under the generated catalog that this run doesn't produce (a token removed from packages/brand). */
function listFiles(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? listFiles(path.join(dir, e.name)) : [path.join(dir, e.name)],
  );
}
const stale = listFiles(path.join(iosRoot, catalog)).filter((f) => !outputs.has(path.relative(iosRoot, f)));

if (check) {
  const outdated = [...outputs].filter(([rel, contents]) => !same(path.join(iosRoot, rel), contents)).map(([rel]) => rel);
  const problems = [...outdated, ...stale.map((f) => `${path.relative(iosRoot, f)} (no longer generated)`), ...iconDrift];
  if (problems.length) {
    console.error(`Brand resources are out of date. Run: node scripts/generate-brand.mjs\n  ${problems.join('\n  ')}`);
    process.exit(1);
  }
  console.log('Brand resources are up to date.');
} else {
  for (const problem of iconDrift) console.warn(`Warning: ${problem}`);
  for (const file of stale) rmSync(file);
  let written = 0;
  for (const [rel, contents] of outputs) {
    const file = path.join(iosRoot, rel);
    if (same(file, contents)) continue;
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, contents);
    written++;
  }
  console.log(`Brand resources: ${written} written, ${outputs.size - written} unchanged, ${stale.length} removed.`);
}

