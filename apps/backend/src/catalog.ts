import { db } from "./db.js";
import { env } from "./env.js";

/** Missing = "published" (docs that predate draft support). */
export type ContentStatus = "draft" | "published";

export interface TranscriptLine {
  startSec: number;
  text: string;
}

export interface EpisodeDoc {
  number: number;
  title: string;
  summary: string;
  durationSec: number;
  transcript: TranscriptLine[];
  takeaways: string[];
  /** Object path in the media bucket, e.g. "books/psychology-of-money/4.mp4". */
  videoPath?: string;
  thumbnailPath?: string;
  status?: ContentStatus;
  updatedAt?: Date;
}

export interface BookDoc {
  _id: string;
  title: string;
  author: string;
  category: string;
  coverTone: string;
  tint: string;
  description: string;
  /**
   * Rendered cover image in the media bucket (2:3 JPEG, e.g. "books/atomic-habits/cover-1a2b3c4d.jpg"),
   * written by the studio worker's `cover` job. Optional: clients draw the coverTone tile without it.
   */
  coverPath?: string;
  /** Position in the catalog listing. */
  order: number;
  episodes: EpisodeDoc[];
  /**
   * "The book in 5 ideas" (Series complete screen), curated by admin or generated by studio.
   * Optional: GraphQL Book.keyIdeas falls back to the episodes' first takeaways when missing or empty.
   */
  keyIdeas?: string[];
  status?: ContentStatus;
  updatedAt?: Date;
}

export const books = db.collection<BookDoc>("books");

/** Written by the studio worker, created by the admin dashboard (see the contracts skill). */
export const studioJobs = db.collection("studio_jobs");

export async function ensureCatalogIndexes() {
  await books.createIndex({ order: 1 });
  // The worker claims the oldest queued job; it creates this index too, which is harmless
  await studioJobs.createIndex({ status: 1, createdAt: 1 });
}

const notDraft = { status: { $ne: "draft" as const } };

/**
 * What the app may see of a book: its episodes cut to the contiguous run of published ones
 * starting at number 1 (the app indexes episodes[number - 1]). Null for a draft book or one
 * with no such episodes. This is the only place public catalog filtering happens.
 */
export function publicBook(book: BookDoc | null): BookDoc | null {
  if (!book || book.status === "draft") return null;
  const sorted = [...book.episodes].sort((a, b) => a.number - b.number);
  const episodes: EpisodeDoc[] = [];
  for (const episode of sorted) {
    if (episode.number !== episodes.length + 1 || episode.status === "draft") break;
    episodes.push(episode);
  }
  return episodes.length ? { ...book, episodes } : null;
}

/** Published catalog for the public GraphQL API, in listing order. */
export async function listPublishedBooks() {
  const docs = await books.find(notDraft).sort({ order: 1 }).toArray();
  return docs.map(publicBook).filter((b): b is BookDoc => b !== null);
}

/** One published book for the public GraphQL API, or null if it's missing or not live. */
export async function getPublishedBook(id: string) {
  return publicBook(await books.findOne({ _id: id, ...notDraft }));
}

/** Public URL for an object in the media bucket, or null when the episode has no file yet. */
export function mediaUrl(path: string | undefined) {
  return path ? `${env.mediaBaseUrl}/${path}` : null;
}
