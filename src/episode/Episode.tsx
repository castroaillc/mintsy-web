import { Audio } from "@remotion/media";
import {
  CalculateMetadataFunction,
  Series,
  staticFile,
  useVideoConfig,
} from "remotion";

import type { EpisodeProps } from "./schema";
import { SceneFrame } from "./SceneFrame";
import { Branded } from "../branding/Branded";
import { INTRO_FRAMES, sceneFrames } from "./timing";
import { VisualView } from "./Visuals";

export const calculateEpisodeMetadata: CalculateMetadataFunction<
  EpisodeProps
> = ({ props }) => ({
  durationInFrames:
    INTRO_FRAMES +
    props.scenes.reduce((sum, s) => sum + sceneFrames(s.audioSec), 0),
});

/** One episode: scenes in order, each with its own narration clip. Generated by the pipeline, so scenes are looped as one template. */
export const Episode: React.FC<EpisodeProps> = ({
  scenes,
  tint,
  bookTitle,
  author,
  chapter,
  episodeTitle,
}) => {
  const { fps } = useVideoConfig();
  return (
    <Branded
      bookTitle={bookTitle}
      chapter={chapter}
      episodeTitle={episodeTitle}
    >
      <Series>
        {scenes.map((scene, i) => (
          <Series.Sequence
            key={i}
            name={`${i + 1} · ${scene.visual.type}`}
            durationInFrames={sceneFrames(scene.audioSec)}
            premountFor={fps}
          >
            <SceneFrame tint={tint}>
              <VisualView
                visual={scene.visual}
                cueSec={scene.cueSec}
                bookTitle={bookTitle}
                author={author}
              />
            </SceneFrame>
            {/* Sample props have no audio */}
            {scene.audio ? <Audio src={staticFile(scene.audio)} /> : null}
          </Series.Sequence>
        ))}
      </Series>
    </Branded>
  );
};
