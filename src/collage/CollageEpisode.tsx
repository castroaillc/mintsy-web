import { Audio } from "@remotion/media";
import {
  AbsoluteFill,
  CalculateMetadataFunction,
  Easing,
  interpolate,
  Series,
  staticFile,
  useCurrentFrame,
  useVideoConfig,
} from "remotion";

import { Branded } from "../branding/Branded";
import { INTRO_FRAMES, sceneFrames } from "../episode/timing";
import { PaperFinish, Stripes } from "./kit";
import { BACKGROUNDS, BeatView, CueContext } from "./Layouts";
import type { CollageEpisodeProps, TimedCollageScene } from "./schema";

export const calculateCollageMetadata: CalculateMetadataFunction<
  CollageEpisodeProps
> = ({ props }) => ({
  durationInFrames:
    INTRO_FRAMES +
    props.scenes.reduce((sum, s) => sum + sceneFrames(s.audioSec), 0),
});

const SLIDE_FRAMES = 14;

/** One scene: its beats in order, each sliding in when its start cue is spoken. */
const CollageSceneView: React.FC<{ scene: TimedCollageScene }> = ({
  scene,
}) => {
  const frame = useCurrentFrame();
  const { fps, durationInFrames } = useVideoConfig();
  const starts = scene.beats.map((b, i) =>
    i === 0
      ? 0
      : (scene.cueSec[b.startCue] ?? (scene.audioSec * i) / scene.beats.length),
  );
  return (
    <CueContext.Provider value={scene.cueSec}>
      <AbsoluteFill>
        {scene.beats.map((b, i) => {
          const from = Math.round(starts[i] * fps);
          const to =
            i + 1 < starts.length
              ? Math.round(starts[i + 1] * fps)
              : durationInFrames + SLIDE_FRAMES;
          if (frame < from - SLIDE_FRAMES || frame > to + SLIDE_FRAMES)
            return null;
          const enter =
            i === 0
              ? 1
              : interpolate(
                  frame,
                  [from - SLIDE_FRAMES / 2, from + SLIDE_FRAMES / 2],
                  [0, 1],
                  {
                    extrapolateLeft: "clamp",
                    extrapolateRight: "clamp",
                    easing: Easing.inOut(Easing.cubic),
                  },
                );
          const leave = interpolate(
            frame,
            [to - SLIDE_FRAMES / 2, to + SLIDE_FRAMES / 2],
            [0, 1],
            {
              extrapolateLeft: "clamp",
              extrapolateRight: "clamp",
              easing: Easing.inOut(Easing.cubic),
            },
          );
          const bg = BACKGROUNDS[b.background];
          return (
            <AbsoluteFill
              key={i}
              style={{ translate: `0 ${(1 - enter - leave) * 720}px` }}
            >
              <Stripes a={bg.a} b={bg.b} />
              <BeatView
                beat={b.beat}
                start={starts[i]}
                background={b.background}
              />
            </AbsoluteFill>
          );
        })}
      </AbsoluteFill>
    </CueContext.Provider>
  );
};

/** A full episode in the collage style. Generated by the pipeline, so scenes are looped as one template. */
export const CollageEpisode: React.FC<CollageEpisodeProps> = ({
  scenes,
  bookTitle,
  chapter,
  episodeTitle,
}) => {
  const { fps } = useVideoConfig();
  return (
    <AbsoluteFill>
      <Branded
        bookTitle={bookTitle}
        chapter={chapter}
        episodeTitle={episodeTitle}
      >
        <Series>
          {scenes.map((scene, i) => (
            <Series.Sequence
              key={i}
              name={`${i + 1} · ${scene.beats.map((b) => b.beat.layout).join(" → ")}`}
              durationInFrames={sceneFrames(scene.audioSec)}
              premountFor={fps}
            >
              <CollageSceneView scene={scene} />
              {scene.audio ? <Audio src={staticFile(scene.audio)} /> : null}
            </Series.Sequence>
          ))}
        </Series>
      </Branded>
      <PaperFinish />
    </AbsoluteFill>
  );
};
